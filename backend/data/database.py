def add_event(event: Dict[str, Any]):
    if isinstance(event.get("timestamp"), datetime):
        event["timestamp"] = event["timestamp"].isoformat()
    EVENTS.insert(0, event)
    
    # Broadcast to connected WebSocket clients
    try:
        loop = asyncio.get_event_loop()
        if loop.is_running():
            # Create a serializable copy of the event
            import copy
            ws_event = copy.deepcopy(event)
            if isinstance(ws_event.get("timestamp"), datetime):
                ws_event["timestamp"] = ws_event["timestamp"].isoformat()
            loop.create_task(manager.broadcast({"type": "new_event", "data": ws_event}))
    except Exception as e:
        print(f"WS error: {e}")
    
    # Store to PostgreSQL vector db
    text_to_embed = f"Event: {event['event_type']}. {event.get('description', '')} Location: {event.get('camera_name', '')}"
    
    embedding_vector = None
    if embed_model:
        embedding_vector = embed_model.encode(text_to_embed).tolist()

    try:
        db = SessionLocal()
        try:
            # Serialize datetime objects for JSON columns
            import copy
            safe_event = copy.deepcopy(event)
            if isinstance(safe_event.get("timestamp"), datetime):
                safe_event["timestamp"] = safe_event["timestamp"].isoformat()
                
            stored_timestamp = event.get("timestamp") or datetime.utcnow()
            if isinstance(stored_timestamp, str):
                try:
                    stored_timestamp = datetime.fromisoformat(stored_timestamp.replace("Z", "+00:00"))
                except ValueError:
                    stored_timestamp = datetime.utcnow()
            db_event = DBEvent(
                id=event["id"],
                camera_id=event["camera_id"],
                camera_name=event.get("camera_name", ""),
                timestamp=stored_timestamp,
                event_type=event["event_type"],
                severity=event["severity"],
                summary=event.get("description", ""),
                person_id=event.get("person_id"),
                clip_ref=event.get("clip_ref"),
                thumbnail=event.get("thumbnail"),
                embedding=embedding_vector,
                raw_data=safe_event
            )
            db.add(db_event)
            db.commit()
        except Exception as inner_e:
            db.rollback()
            raise inner_e
        finally:
            db.close()
    except Exception as e:
        print(f"Warning: Could not save event to the analytics database: {e}")
    if event.get("severity") in ["critical", "high"]:
        inc_id = f"INC_{uuid.uuid4().hex[:8].upper()}"
        INCIDENTS.insert(0, {
            "id": inc_id,
            "title": f"Escalated: {event['event_type'].replace('_', ' ').title()}",
            "summary": event.get("description", "Auto-escalated incident based on AI analysis."),
            "severity": event["severity"],
            "status": "open",
            "created_at": event["timestamp"],
            "event_ids": [event["id"]],
            "camera_ids": [event["camera_id"]],
            "person_ids": [event.get("person_id")] if event.get("person_id") else [],
            "timeline": [{
                "timestamp": event["timestamp"],
                "description": f"Event {event['id']} generated by {event['camera_id']} and auto-escalated."
            }]
        })
