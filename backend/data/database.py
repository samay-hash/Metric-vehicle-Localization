def SYSTEM_STATS():
    # Attempt to fetch real hardware metrics
    cpu_percent = 0
    mem_percent = 0
    gpu_util = 0
    gpu_mem = 0
    
    try:
        import psutil
        cpu_percent = psutil.cpu_percent(interval=None)
        mem_percent = psutil.virtual_memory().percent
    except ImportError:
        pass
        
    try:
        import pynvml
        pynvml.nvmlInit()
        handle = pynvml.nvmlDeviceGetHandleByIndex(0)
        gpu_util = pynvml.nvmlDeviceGetUtilizationRates(handle).gpu
        mem_info = pynvml.nvmlDeviceGetMemoryInfo(handle)
        gpu_mem = round((mem_info.used / mem_info.total) * 100)
    except Exception:
        pass

    return {
        "cameras_online": sum(1 for c in CAMERAS if c["status"] == "active"),
        "cameras_warning": sum(1 for c in CAMERAS if c["status"] == "warning"),
        "cameras_offline": sum(1 for c in CAMERAS if c["status"] == "offline"),
        "events_today": len(EVENTS),
        "critical_events": sum(1 for e in EVENTS if e["severity"] == "critical"),
        "high_events": sum(1 for e in EVENTS if e["severity"] == "high"),
        "pending_review": sum(1 for e in EVENTS if e["status"] == "pending_review"),
        "active_incidents": len(INCIDENTS),
        "hardware": {
            "cpu": cpu_percent,
            "ram": mem_percent,
            "gpu_util": gpu_util,
            "gpu_mem": gpu_mem
        }
    }
